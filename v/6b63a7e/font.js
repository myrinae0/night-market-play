export const FONTS = {
  big: { h: 7, space: 3, glyphs: B },
  small: { h: 5, space: 2, glyphs: S },
};

// Characters the game's text uses (gate labels, counts, HUD, hints, banners).
export const REQUIRED_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+-−×÷?!.,:\'%/()<>=';

function glyph(font, ch) {
  const g = font.glyphs[ch];
  return g || null;
}

// Width in pixels of `str` (upper-cased) at scale 1, without outline.
export function textWidth(str, fontName = 'big') {
  const font = FONTS[fontName];
  let w = 0, n = 0;
  for (const ch of String(str).toUpperCase()) {
    const g = glyph(font, ch);
    w += g ? g[0].length : font.space;
    n += 1;
  }
  return Math.max(0, w + n - 1);
}

// Lays out `str` at integer `scale` into a mask (see top). The outline is 1 px
// all round and the shadow 1 px below, whatever the scale, so the result is
// (textWidth * scale + 2) x (h * scale + 3).
export function textMask(str, fontName = 'big', scale = 1) {
  const font = FONTS[fontName];
  const s = Math.max(1, Math.round(scale));
  const tw = textWidth(str, fontName) * s;
  const w = tw + 2, h = font.h * s + 3;
  const m = new Uint8Array(w * h);
  let x0 = 1;
  for (const ch of String(str).toUpperCase()) {
    const g = glyph(font, ch);
    if (!g) { x0 += (font.space + 1) * s; continue; }
    for (let y = 0; y < font.h; y++) {
      for (let x = 0; x < g[y].length; x++) {
        if (g[y][x] !== '#') continue;
        for (let yy = 0; yy < s; yy++) for (let xx = 0; xx < s; xx++) m[(1 + y * s + yy) * w + x0 + x * s + xx] = 2;
      }
    }
    x0 += (g[0].length + 1) * s;
  }
  // Outline (8-neighbourhood) and a drop shadow one pixel below.
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (m[y * w + x]) continue;
    let hit = false;
    for (let dy = -1; dy <= 1 && !hit; dy++) for (let dx = -1; dx <= 1; dx++) {
      const yy = y + dy, xx = x + dx;
      if (yy >= 0 && yy < h && xx >= 0 && xx < w && m[yy * w + xx] === 2) { hit = true; break; }
    }
    if (!hit && y >= 2 && m[(y - 2) * w + x] === 2) hit = true; // shadow
    if (hit) m[y * w + x] = 1;
  }
  return { w, h, mask: m };
}

// Splits text into lines no wider than maxW pixels (at the given scale).
export function wrapText(str, maxW, fontName = 'big', scale = 1) {
  const words = String(str).split(/\s+/).filter(Boolean);
  const lines = [];
  let cur = '';
  for (const w of words) {
    const t = cur ? `${cur} ${w}` : w;
    if (cur && textWidth(t, fontName) * scale > maxW) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}
